def _sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _display(path: Path) -> str:
    return path.relative_to(ROOT).as_posix()


def _verify_historical_artifacts() -> None:
    for path, expected in EXPECTED_HISTORICAL_SHA256.items():
        if not path.is_file():
            raise RuntimeError(f"missing frozen historical artifact: {_display(path)}")
        actual = _sha(path)
        if actual != expected:
            raise RuntimeError(
                f"historical artifact changed: {_display(path)} "
                f"(expected {expected}, found {actual})"
            )


def _verify_baseline_sources(v3: dict[str, Any]) -> dict[str, dict[str, str]]:
    sources = v3["comparison_inputs_verified_at_correction"]["sources"]
    if not set(BASELINE_KEYS).issubset(sources):
        raise RuntimeError("V3 is missing one or more prompt-generated baseline receipts")

    receipts: dict[str, dict[str, str]] = {}
    for key in BASELINE_KEYS:
        source = sources[key]
        path = ROOT / source["path"]
        if path.suffix != ".py" or not path.is_file():
            raise RuntimeError(f"baseline is not a readable Python source: {key}")
        actual = _sha(path)
        if actual != source["sha256"]:
            raise RuntimeError(f"baseline source no longer matches V3 receipt: {key}")
        text = path.read_text()
        if "def score(" not in text or "import re" not in text:
            raise RuntimeError(f"baseline lacks the expected executable regex scorer: {key}")
        if key == "a104_v2_holistic" and "tanh" not in text:
            raise RuntimeError("v2 holistic baseline lacks its recorded tanh mechanism")
        receipts[key] = {
            "artifact_role": "prompt_generated_shallow_executable_code",
            "runtime_channel": "code",
            "language": "Python",
            "path": source["path"],
            "sha256": actual,
            "mechanisms": BASELINE_MECHANISMS[key],
        }
    return receipts


def _numeric_leaves(value: Any, path: str = "") -> dict[str, int | float]:
    """Return non-boolean numeric leaves, keyed by their JSON-pointer-like path."""
    output: dict[str, int | float] = {}
    if isinstance(value, dict):
        for key, child in value.items():
            output.update(_numeric_leaves(child, f"{path}/{key}"))
    elif isinstance(value, list):
        for index, child in enumerate(value):
            output.update(_numeric_leaves(child, f"{path}/{index}"))
    elif isinstance(value, (int, float)) and not isinstance(value, bool):
        output[path] = value
    return output


