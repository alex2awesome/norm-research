"""Publish the additive a104 V4 channel-taxonomy correction.

V3's empirical values and provenance receipts are retained.  Its comparison
language, however, can be misread as a direct prompt-articulability versus
code-verifiability experiment.  The three artifacts behind the historical
``prompt_compiled_baseline`` label are Python scorers generated by Claude:
their *authoring origin* is an LLM prompt, but their *runtime channel* is code.

V4 therefore describes the result as a within-code-channel comparison between
prompt-generated shallow executable programs, a pre-existing deeper static/AST
program, and a retrospective relation program.  Spearman rho remains agreement
with the frozen LLM-judgment reference.  It is not, by itself, an isomorphism
certificate; that term is reserved here for joint construct, input, program,
and reference fidelity.

This script performs no model/API/GPU calls and reads no external anchor.  Run
it once to create the three additive V4 artifacts, then use ``--check`` to
rebuild them in memory and require byte-for-byte equality.
"""
