def render_report(v4: dict[str, Any]) -> str:
    rhos = v4["heldout_rhos_common_intersection"]
    deep = v4["preexisting_deep_coded_checker"]
    h0 = v4["retrospective_relation_h0"]
    receipt = v4["channel_taxonomy_correction_receipt"]
    return f"""# Active coding census a104 — channel-taxonomy correction (V4)

## Corrected result

All empirical values and V3 provenance receipts are unchanged. On the common
held-out intersection (`n={v4['common_heldout_n']}`), the TRAIN-selected
prompt-generated shallow Python scorer (legacy JSON key
`prompt_compiled_baseline`) has Spearman rho
`{rhos['prompt_compiled_baseline']:.16f}` with the frozen LLM judgment. The
pre-existing deep static/AST code program has rho
`{rhos['preexisting_deep_coded_checker']:.16f}`
(delta `{deep['delta_vs_prompt_baseline']:+.16f}`, P(gate)
`{deep['P_gate']:.4f}`, P(beats) `{deep['P_beats_baseline']:.4f}`) and passes the
current pooled gate. The retrospective relation code program has rho
`{rhos['retrospective_relation_h0']:.16f}`
(delta `{h0['delta_vs_prompt_baseline']:+.16f}`, P(gate)
`{h0['P_gate']:.4f}`, P(beats) `{h0['P_beats_baseline']:.4f}`) and remains
sub-gate.

The warranted conclusion is narrower and cleaner: **the pre-existing deep
executable-code program reconstructs the frozen LLM judgment better than the
selected prompt-generated shallow executable-code program on this support.**
This is a within-code-channel program-depth comparison. It is not a direct
prompt-articulability versus code-verifiability comparison and is not a
code-over-prompt result.

## Why the channel label changed

All three historical “prompt-compiled” flavors are frozen Claude-generated
Python functions. Their mechanisms are regex keyword hits, regex
density/coverage, and regex plus weighted/tanh saturation. Prompt generation is
their authoring provenance; at evaluation time they are executable code. The
deep static/AST checker and retrospective `CodeOps` h0 are executable code too.
There is no direct prompt-output candidate pole in this a104 comparison.

The legacy key `prompt_compiled_baseline` remains in V4 so numerical paths and
downstream checks do not move. V4's `channel_taxonomy_v4` records its corrected
meaning explicitly.

## Four separate questions

- **Articulability** is prompt-based implementation. It is not measured as a
  candidate channel here.
- **Verifiability** is code-based executable implementation. The compared
  candidate programs all run in this channel, at different depths and with
  different authoring provenance.
- **Reconstruction agreement** is what the reported Spearman rho estimates:
  agreement with the frozen articulated LLM-judgment reference.
- **Isomorphism** is reserved for joint construct, input-representation,
  program-channel, and reference-instrument fidelity. Correlation alone does
  not certify it, so this artifact reports isomorphism as not certified.

No disagreement is adjudicated against external truth. Higher rho does not show
that code is correct where it differs from the LLM reference, and a lower rho
does not show tacitness.

## Provenance retained from V3

V3's manual/mock label-unreferenced—not label-inaccessible—classification for
the retrospective h0 is unchanged. Its corpus lineage, frozen input/program
hashes, comparison-source receipts, model-artifact disclosures, structural
coverage counts, and limitations are copied exactly into V4. No external
supervised anchor, model/API call, repository execution, or GPU was used for
this correction. The objective remains unsupervised reconstruction of the
articulated prompt judgment.

The correction is bound to V3 JSON SHA-256 `{receipt['v3_json']['sha256']}` and
V3 report SHA-256 `{receipt['v3_report']['sha256']}`.
"""


