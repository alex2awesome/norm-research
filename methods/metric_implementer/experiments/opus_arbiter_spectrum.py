#!/usr/bin/env python3
# pylint: disable=line-too-long
"""
================================================================================
OPUS ARBITER — agent brief for pairwise same/different labeling
(peer-review rubric statements)
================================================================================

>>> WHO YOU ARE AND WHY YOU'RE HERE <<<

You are an Opus agent running in the Claude Code CLI. A research pipeline has produced
several clusterings of ~3,257 peer-review rubric statements (one built by a Llama judge
= the "existing" partition; others by a GLM-4.7 model). To decide which clustering is
actually best — and to calibrate where embedding-similarity stops predicting "same
criterion" — we need an INDEPENDENT, family-neutral gold-standard set of pairwise
same/different labels. You (Opus) are that gold standard: you are a different model family
from both Llama (which built the old partition) and GLM (which built the candidate
partitions and which already produced its own label set). Your labels confirm or correct
the GLM-5.2 labels and are the reference everything is scored against. Be careful and
consistent — quality matters more than speed.

>>> EXACTLY WHAT TO DO (step by step) <<<

1. READ the input file:
     outputs/analyses/spectrum_pairs.jsonl
   It is JSONL: one object per line, ~3000 lines. Each line has:
     pid    int    -- pair id (use as the key in your output)
     key_a  str    -- internal form id for statement A (ignore when judging)
     key_b  str    -- internal form id for statement B (ignore when judging)
     text_a str    -- statement A  (judge THIS)
     text_b str    -- statement B  (judge THIS)
     sim    float  -- embedding cosine similarity. *** IGNORE THIS WHEN JUDGING. ***
                     It exists only so the sample spans the similarity spectrum; letting
                     it bias your label would defeat the purpose.

2. RESUME if partly done: if outputs/analyses/spectrum_opus_labels.jsonl already exists,
   read the pids already present and skip them. Append new labels; never rewrite or
   duplicate a pid. This makes the job crash-safe.

3. JUDGE each not-yet-done pair using the EXACT prompt below (JUDGE_PROMPT) — the same
   prompt the GLM-5.2 arbiter used, so the only difference between the two label sets is
   the judge, not the instructions. Label scale:
     2 = SAME criterion. One statement is merely a REPHRASING of the other — the identical
         evaluative judgment on the same aspect, just worded differently.
         e.g. "The literature review should be thorough and recent"
              vs "The work should comprehensively cover up-to-date relevant literature" -> 2
     1 = RELATED but genuinely DIFFERENT / borderline. Same general area, distinct
         sub-aspects, or genuinely unclear.
         e.g. "Citations should be complete" vs "References should follow journal style" -> 1
     0 = DIFFERENT criteria. Distinct aspects of the work, even if topically related or
         commonly co-assessed.
         e.g. "The statistical analysis should be appropriate"
              vs "The abstract should be an accurate summary" -> 0
   Rules: "same topic" is NOT "same criterion". Surface restatements (active/passive,
   "should" vs "must", synonym swaps) are 2; a different object/scope of evaluation is 0/1.
   Judge each pair INDEPENDENTLY — do not let earlier pairs anchor later ones. Be
   conservative with 2 (only when truly the same judgment).

4. WORK IN BATCHES for efficiency (e.g. 25-50 pairs per turn), but apply the judgment
   independently to every pair. You may present the pairs to yourself using the
   JUDGE_PROMPT format below.

5. WRITE your labels to EXACTLY this path (this is where downstream code reads them):
     outputs/analyses/spectrum_opus_labels.jsonl
   Format: JSONL, one object per line, EXACTLY:  {"pid": <int>, "label": <int>}
   label must be the integer 2, 1, or 0. One line per input pid. Write incrementally
   (append + flush as you complete batches) so progress is never lost.

>>> WHEN YOU ARE DONE <<<

Report: how many pairs labeled, and the label distribution (# of 2 / 1 / 0). Do not
delete or modify spectrum_pairs.jsonl or any other file. Leave only
spectrum_opus_labels.jsonl as your output.

>>> REPRODUCIBILITY NOTE (for reference; you do NOT need to run this) <<<

The input sample spectrum_pairs.jsonl was generated by sample() in this file: embed all
peer-review forms with OpenAI text-embedding-3-small, then draw ~150 pairs per 0.05 cosine-
similarity bin (so the full spectrum, including the high-sim transition, is well-covered).
The exact judge instructions are JUDGE_PROMPT below. Run `python -m ...opus_arbiter_spectrum`
only to (re)generate the sample or print this brief — there is no API code here; the
labeling is done by YOU, the agent.
================================================================================
"""

from __future__ import annotations
import json, os, sys

PAIRS_FILE = sys.argv[1] if len(sys.argv) > 1 else "outputs/analyses/spectrum_pairs.jsonl"
LABELS_FILE = sys.argv[2] if len(sys.argv) > 2 else "outputs/analyses/spectrum_opus_labels.jsonl"   # <<< agent writes labels HERE

# ---- EXACT judge prompt used by the GLM-5.2 arbiter (reuse verbatim; only the judge differs) ----
# {listing} is the numbered list of pairs, formatted as:  [pid] A: "..." | B: "..."
JUDGE_PROMPT = (
    "You are an expert peer-review rubric judge. For each pair, decide if they express the "
    "SAME evaluation criterion (one is merely a rephrasing of the other — identical judgment in "
    "different words) or DIFFERENT criteria (they evaluate distinct aspects, even if topically related).\n\n"
    "Label: 2 = SAME criterion (rephrased), 1 = related but genuinely different / borderline, "
    "0 = DIFFERENT criteria.\n\n"
    "Judge each pair independently and conservatively (only 2 if truly the same judgment). "
    'Return ONLY a JSON array, one entry per pair in order: [{"pid":0,"label":2},...]\n\n'
    "Pairs:\n{listing}"
)


def print_brief():
    """Print the spec summary (the full agent brief is the module docstring above)."""
    print("=" * 80)
    print("SPEC SUMMARY")
    print("=" * 80)
    print(f"INPUT  (read):      {os.path.abspath(PAIRS_FILE)}")
    print(f"OUTPUT (write):     {os.path.abspath(LABELS_FILE)}")
    print(f"OUTPUT line format: {{\"pid\": <int>, \"label\": <2|1|0>}}")
    if os.path.exists(PAIRS_FILE):
        n = sum(1 for _ in open(PAIRS_FILE))
        print(f"INPUT pairs:        {n}")
    else:
        print("INPUT pairs:        (file missing — run sample() to generate)")
    print("\nEXACT JUDGE PROMPT (use verbatim; same as GLM-5.2 arbiter):\n")
    print(JUDGE_PROMPT.replace("{listing}", "[0] A: \"<text_a>\" | B: \"<text_b>\"\n[1] A: ... | B: ..."))


def sample():
    """Regenerate spectrum_pairs.jsonl: ~150 pairs per 0.05 cosine-similarity bin from ALL
    peer-review forms (OpenAI text-embedding-3-small embeddings). Deterministic (seed=7)."""
    import numpy as np, random
    os.environ.setdefault("GLMCLUSTER_EMB_CACHE", "outputs/analyses/emb_all_cache")
    from methods.metric_implementer.experiments.glm_cluster import load_forms, get_embeddings
    keys, texts = load_forms("peer-review", n_forms=None)
    key2text = dict(zip(keys, texts))
    E = np.asarray(get_embeddings(texts, keys, "peer-review", "openai", "text-embedding-3-small"), dtype=np.float32)
    E /= (np.linalg.norm(E, axis=1, keepdims=True) + 1e-12)
    n = len(keys)
    iu = np.triu_indices(n, 1)
    sims = (E @ E.T)[iu].astype(np.float32)
    ka, kb = np.array(keys)[iu[0]], np.array(keys)[iu[1]]
    binidx = np.clip((sims / 0.05).astype(int), 0, 19)
    rng = random.Random(7)
    picked = []
    for b in range(20):
        idxs = np.where(binidx == b)[0]
        if len(idxs) == 0:
            continue
        sel = sorted(rng.sample(range(len(idxs)), min(150, len(idxs))))
        picked.extend(int(x) for x in idxs[sel])
    with open(PAIRS_FILE, "w") as f:
        for pid, s in enumerate(picked):
            f.write(json.dumps({"pid": pid, "key_a": ka[s], "key_b": kb[s],
                                "text_a": key2text.get(ka[s], ""), "text_b": key2text.get(kb[s], ""),
                                "sim": round(float(sims[s]), 3)}) + "\n")
    print(f"sampled {len(picked)} pairs -> {PAIRS_FILE}")


def main():
    if not os.path.exists(PAIRS_FILE):
        print("spectrum_pairs.jsonl missing — generating via sample() ...")
        sample()
    print_brief()


if __name__ == "__main__":
    main()
