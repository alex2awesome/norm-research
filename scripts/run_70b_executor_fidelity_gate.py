"""Legacy circular cross-executor diagnostic (not an executor fidelity gate).

The frozen source behavior was generated by the incumbent 8B executor, so agreement
with it cannot select between 8B and 70B.  New executor selection must use
``experiments.ceiling_ladder`` and its independent Sonnet/planted references.
"""
